def replace_in_para(idx, old, new):
    """在段落中做精确文本替换（保留格式）"""
    p = doc.paragraphs[idx]
    for run in p.runs:
        if old in run.text:
            run.text = run.text.replace(old, new)
            return True
    # fallback: try across runs
    full = p.text
    if old in full:
        # rebuild
        new_full = full.replace(old, new)
        for run in p.runs:
            run.text = ""
        if p.runs:
            p.runs[0].text = new_full
        return True
    return False

def replace_para(idx, new_text):
    """替换整段文字"""
    p = doc.paragraphs[idx]
    for run in p.runs:
        run.text = ""
    if p.runs:
        p.runs[0].text = new_text
    else:
        p.add_run(new_text)

