def replace_in_para(idx, old, new):
    p = doc.paragraphs[idx]
    for run in p.runs:
        if old in run.text:
            run.text = run.text.replace(old, new)
            return True
    full = p.text
    if old in full:
        new_full = full.replace(old, new)
        for run in p.runs:
            run.text = ""
        if p.runs:
            p.runs[0].text = new_full
        return True
    return False

