def replace_para_text(idx, old_full, new_full):
    """替换整个段落文本，保留第一个run的格式"""
    p = doc.paragraphs[idx]
    if p.text.strip() != old_full.strip():
        # 尝试部分匹配
        if old_full.strip() not in p.text:
            print(f"[{idx}] WARN: text mismatch, skipping")
            return False
    # 保留格式：清空所有run，在第一个run中写入新文本
    if p.runs:
        fmt = p.runs[0].font
        for run in p.runs:
            run.text = ""
        p.runs[0].text = new_full
    return True

def replace_in_para(idx, old, new):
    """段落内局部替换"""
    p = doc.paragraphs[idx]
    for run in p.runs:
        if old in run.text:
            run.text = run.text.replace(old, new)
            return True
    full = p.text
    if old in full:
        new_full = full.replace(old, new)
        for run in p.runs:
            run.text = ""
        if p.runs:
            p.runs[0].text = new_full
        return True
    return False

